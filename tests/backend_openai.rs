//! `openai_api` backend through the real binary, against a mock OpenAI-compatible
//! server (prd.md `type: openai_api` fields, Error Handling exit 9/10/11).
//!
//! `litellm-rs`'s `install_default_runtime` is a process-wide `OnceLock`, so every
//! test here drives the real `ccm` binary as a *subprocess* (via `spawn_blocking`)
//! rather than linking litellm-rs into this test binary directly — each subprocess
//! gets a fresh `OnceLock`, and this also exercises the real argv/exit-code/stdio
//! surface end to end.

mod common;

use common::Fixture;
use predicates::prelude::PredicateBooleanExt;
use serde_json::json;
use wiremock::matchers::{header, method, path};
use wiremock::{Mock, MockServer, ResponseTemplate};

fn api_yaml(base_url: &str, timeout_secs: u64, extra: &str) -> String {
    format!(
        "- name: omniroute\n  type: openai_api\n  prompt: default\n  base_url: {base_url}\n  model: gpt-5.4\n  api_key:\n    env: CCM_TEST_KEY\n  timeout: {timeout_secs}\n{extra}"
    )
}

const PROMPTS_YAML: &str =
    "default:\n  system: |\n    You are helpful.\n  template: write a commit message\n";

fn setup(fx: &Fixture) {
    fx.init_git();
    fx.write("a.txt", "hello\n");
    fx.stage("a.txt");
}

fn success_response(content: &str) -> ResponseTemplate {
    ResponseTemplate::new(200).set_body_json(json!({
        "id": "cmpl-1",
        "object": "chat.completion",
        "created": 1,
        "model": "gpt-5.4",
        "choices": [
            {"index": 0, "message": {"role": "assistant", "content": content}, "finish_reason": "stop"}
        ],
        "usage": {"prompt_tokens": 1, "completion_tokens": 1, "total_tokens": 2}
    }))
}

#[tokio::test(flavor = "multi_thread")]
async fn happy_path_dry_run_prints_the_raw_message_to_stdout() {
    let server = MockServer::start().await;
    Mock::given(method("POST"))
        .and(path("/v1/chat/completions"))
        .respond_with(success_response("feat: add a.txt"))
        .expect(1)
        .mount(&server)
        .await;

    let fx = Fixture::new();
    setup(&fx);
    fx.write_config(
        &api_yaml(&format!("{}/v1", server.uri()), 30, ""),
        PROMPTS_YAML,
    );

    let mut cmd = fx.ccm();
    cmd.env("CCM_TEST_KEY", "sk-test")
        .args(["--dry-run", "--config"])
        .arg(fx.config_dir());
    let assert = tokio::task::spawn_blocking(move || cmd.assert())
        .await
        .unwrap();
    assert
        .code(0)
        .stdout("feat: add a.txt")
        .stderr(predicates::str::contains(
            "Commit message generated by omniroute (gpt-5.4)",
        ));
}

