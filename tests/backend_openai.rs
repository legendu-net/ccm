#[tokio::test(flavor = "multi_thread")]
async fn non_json_garbage_response_is_exit_10_or_11() {
    // litellm-rs may classify a transport-level parse failure as either a call
    // failure or a malformed-response error; pin whichever it actually does today so
    // a future litellm-rs upgrade that changes it fails loudly here rather than
    // silently.
    let server = MockServer::start().await;
    Mock::given(method("POST"))
        .and(path("/v1/chat/completions"))
        .respond_with(ResponseTemplate::new(200).set_body_string("not json at all"))
        .mount(&server)
        .await;

    let fx = Fixture::new();
    setup(&fx);
    fx.write_config(
        &api_yaml(&format!("{}/v1", server.uri()), 30, ""),
        PROMPTS_YAML,
    );

    let mut cmd = fx.ccm();
    cmd.env("CCM_TEST_KEY", "sk-test")
        .args(["--dry-run", "--config"])
        .arg(fx.config_dir());
    let assert = tokio::task::spawn_blocking(move || cmd.assert())
        .await
        .unwrap();
    let output = assert.get_output();
    let code = output.status.code().unwrap();
    assert!(code == 10 || code == 11, "unexpected exit code {code}");
}

