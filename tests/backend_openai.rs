#[tokio::test(flavor = "multi_thread")]
async fn a_non_2xx_plain_text_body_surfaces_only_the_status_accepted_limitation() {
    // prd.md requires the response body always be surfaced alongside the status for
    // exit 10. litellm-rs only does that when the body is a standard OpenAI-shaped
    // {"error": {"message": ...}} JSON envelope (see the sibling test below) — for
    // any other shape (plain text here), it discards the real body internally before
    // ccm's code ever sees it and reports only "Server error: <status>". Escalated to
    // and accepted by the user as a documented limitation of the mandated dependency
    // (see backend/openai.rs's module docs and findings.md) rather than switching off
    // litellm-rs. This test pins that *actual* behavior so a litellm-rs upgrade that
    // changes it is caught.
    let server = MockServer::start().await;
    Mock::given(method("POST"))
        .and(path("/v1/chat/completions"))
        .respond_with(
            ResponseTemplate::new(500).set_body_string("omniroute: no upstream available"),
        )
        .mount(&server)
        .await;

    let fx = Fixture::new();
    setup(&fx);
    fx.write_config(
        &api_yaml(&format!("{}/v1", server.uri()), 30, ""),
        PROMPTS_YAML,
    );

    let mut cmd = fx.ccm();
    cmd.env("CCM_TEST_KEY", "sk-test")
        .args(["--dry-run", "--config"])
        .arg(fx.config_dir());
    let assert = tokio::task::spawn_blocking(move || cmd.assert())
        .await
        .unwrap();
    assert.code(10).stderr(
        predicates::str::contains("500")
            .and(predicates::str::contains("omniroute: no upstream available").not()),
    );
}

