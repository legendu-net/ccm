#[tokio::test(flavor = "multi_thread")]
async fn request_body_has_system_only_when_configured_and_user_is_template_plus_diff() {
    let server = MockServer::start().await;
    Mock::given(method("POST"))
        .and(path("/v1/chat/completions"))
        .respond_with(success_response("feat: x"))
        .mount(&server)
        .await;

    let fx = Fixture::new();
    setup(&fx);
    fx.write_config(
        &api_yaml(&format!("{}/v1", server.uri()), 30, ""),
        PROMPTS_YAML,
    );

    let mut cmd = fx.ccm();
    cmd.env("CCM_TEST_KEY", "sk-test")
        .args(["--dry-run", "--config"])
        .arg(fx.config_dir());
    let assert = tokio::task::spawn_blocking(move || cmd.assert())
        .await
        .unwrap();
    assert.code(0);

    let requests = server.received_requests().await.unwrap();
    assert_eq!(requests.len(), 1);
    let body: serde_json::Value = requests[0].body_json().unwrap();
    assert_eq!(body["messages"][0]["role"], "system");
    assert_eq!(body["messages"][0]["content"], "You are helpful.\n");
    assert_eq!(body["messages"][1]["role"], "user");
    let user_content = body["messages"][1]["content"].as_str().unwrap();
    assert!(user_content.starts_with("write a commit message\n\n"));
    assert!(user_content.contains("a.txt"));
}

