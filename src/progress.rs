//! Every step-by-step progress line `ccm` reports, centralized in one place (prd.md
//! "Progress logging"). All of it goes to stderr, never stdout, regardless of
//! `--dry-run` — stdout is reserved for the generated message under `--dry-run` and
//! `--gen-config`'s report. Each function is generic over `Write` so callers can target
//! the real stderr in production and an in-memory buffer in tests.
//!
//! The wording is implemented verbatim from the spec, including its inconsistencies
//! (e.g. `Generating commit message using <name> (<model>)…` uses a `…` ellipsis and no
//! colon, while `Generating diff using: <command>` uses a colon and no ellipsis) —
//! these read as intentional, not typos, so they're preserved rather than normalized.
//!
//! `generated_empty_message`/`commit_message_generated` additionally take a
//! `resolved_model`, folded into the `(<model>)` portion as `<model> => <resolved>`
//! when it's known and differs: `openai_api` entries can route through a gateway (e.g.
//! OmniRoute) that picks the real upstream model dynamically, which the configured
//! `<model>` doesn't capture on its own. This isn't from prd.md's "Progress logging"
//! list — neither is [`raw_message`]/[`cleaned_message`], which dump the backend's
//! response before and after `cleanup::clean_message` so a fence/quote-stripping bug
//! (or an LLM's own formatting choice) is visible directly in the log rather than only
//! inferable from the final message.

use std::io::{self, Write};

pub fn enumerating_working_copy_files(
    out: &mut (impl Write + ?Sized),
    command: &str,
) -> io::Result<()> {
    writeln!(out, "Enumerating working-copy files using: {command}")
}

pub fn working_copy_files_enumerated(
    out: &mut (impl Write + ?Sized),
    command: &str,
) -> io::Result<()> {
    writeln!(out, "Working-copy files enumerated by: {command}")
}

pub fn generating_diff(out: &mut (impl Write + ?Sized), command: &str) -> io::Result<()> {
    writeln!(out, "Generating diff using: {command}")
}

pub fn generating_commit_message(
    out: &mut (impl Write + ?Sized),
    name: &str,
    model: &str,
) -> io::Result<()> {
    writeln!(out, "Generating commit message using {name} ({model})…")
}

/// The backend's response exactly as returned, before `cleanup::clean_message` strips
/// any wrapping code fence or quotes.
pub fn raw_message(out: &mut (impl Write + ?Sized), message: &str) -> io::Result<()> {
    writeln!(out, "Raw message:\n{message}")
}

/// The response after `cleanup::clean_message`, whether or not it actually changed
/// anything — identical output to `raw_message` confirms cleanup was a no-op.
pub fn cleaned_message(out: &mut (impl Write + ?Sized), message: &str) -> io::Result<()> {
    writeln!(out, "Cleaned message:\n{message}")
}

pub fn generated_empty_message(
    out: &mut (impl Write + ?Sized),
    name: &str,
    model: &str,
    resolved_model: Option<&str>,
) -> io::Result<()> {
    writeln!(
        out,
        "Generated empty message using {name} ({})",
        format_model(model, resolved_model)
    )
}

pub fn commit_message_generated(
    out: &mut (impl Write + ?Sized),
    name: &str,
    model: &str,
    resolved_model: Option<&str>,
) -> io::Result<()> {
    writeln!(
        out,
        "Commit message generated by {name} ({})",
        format_model(model, resolved_model)
    )
}

/// Formats the `(<model>)` portion of a progress line, folding in the real upstream
/// model a gateway resolved `model` to (e.g. `gpt-5.4 => gemini-3.5-flash`) when that's
/// known and differs from what was configured. Plain `model` alone covers both the
/// common case (no gateway, or the gateway used exactly what was configured) and
/// `agent_cli` entries, which never resolve to anything else.
fn format_model(model: &str, resolved_model: Option<&str>) -> String {
    match resolved_model {
        Some(resolved) if resolved != model => format!("{model} => {resolved}"),
        _ => model.to_string(),
    }
}

pub fn committing_using(out: &mut (impl Write + ?Sized), command: &str) -> io::Result<()> {
    writeln!(out, "Committing using: {command}")
}

pub fn committed_using(out: &mut (impl Write + ?Sized), command: &str) -> io::Result<()> {
    writeln!(out, "Committed using: {command}")
}

/// A blank line separating one group of progress lines (e.g. everything logged by a
/// single pipeline stage) from the next, so related lines visually cluster together
/// instead of running into one undifferentiated block.
pub fn blank_line(out: &mut (impl Write + ?Sized)) -> io::Result<()> {
    writeln!(out)
}

/// Logged once the tool picker's `fzf` front-end couldn't run (not on `$PATH`, no
/// controlling terminal, or any other failure — see `fzf::FzfOutcome::Unavailable`)
/// before `ccm` falls back to the numbered stdin prompt, so the fallback doesn't look
/// like it happened for no reason.
pub fn fzf_unavailable(out: &mut (impl Write + ?Sized), reason: &str) -> io::Result<()> {
    writeln!(
        out,
        "fzf unavailable ({reason}), falling back to the numbered picker"
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn captured(f: impl FnOnce(&mut Vec<u8>) -> io::Result<()>) -> String {
        let mut buf = Vec::new();
        f(&mut buf).unwrap();
        String::from_utf8(buf).unwrap()
    }

    #[test]
    fn enumeration_lines_match_spec_wording() {
        assert_eq!(
            captured(|w| enumerating_working_copy_files(w, "jj diff --summary")),
            "Enumerating working-copy files using: jj diff --summary\n"
        );
        assert_eq!(
            captured(|w| working_copy_files_enumerated(w, "jj diff --summary")),
            "Working-copy files enumerated by: jj diff --summary\n"
        );
    }

    #[test]
    fn diff_lines_match_spec_wording() {
        assert_eq!(
            captured(|w| generating_diff(w, "git diff --staged")),
            "Generating diff using: git diff --staged\n"
        );
    }

    #[test]
    fn message_generation_lines_match_spec_wording_including_ellipsis() {
        assert_eq!(
            captured(|w| generating_commit_message(w, "OmniRoute", "gpt-5.4")),
            "Generating commit message using OmniRoute (gpt-5.4)…\n"
        );
        assert_eq!(
            captured(|w| generated_empty_message(w, "OmniRoute", "gpt-5.4", None)),
            "Generated empty message using OmniRoute (gpt-5.4)\n"
        );
        assert_eq!(
            captured(|w| commit_message_generated(w, "OmniRoute", "gpt-5.4", None)),
            "Commit message generated by OmniRoute (gpt-5.4)\n"
        );
    }

    #[test]
    fn raw_and_cleaned_message_lines_carry_the_message_verbatim() {
        assert_eq!(
            captured(|w| raw_message(w, "```\nfeat: add x\n```")),
            "Raw message:\n```\nfeat: add x\n```\n"
        );
        assert_eq!(
            captured(|w| cleaned_message(w, "feat: add x")),
            "Cleaned message:\nfeat: add x\n"
        );
    }

    #[test]
    fn resolved_model_is_folded_into_the_model_parens_when_it_differs() {
        assert_eq!(
            captured(|w| commit_message_generated(
                w,
                "OmniRoute",
                "gpt-5.4",
                Some("gemini-3.1-flash-lite")
            )),
            "Commit message generated by OmniRoute (gpt-5.4 => gemini-3.1-flash-lite)\n"
        );
        assert_eq!(
            captured(|w| generated_empty_message(
                w,
                "OmniRoute",
                "gpt-5.4",
                Some("gemini-3.1-flash-lite")
            )),
            "Generated empty message using OmniRoute (gpt-5.4 => gemini-3.1-flash-lite)\n"
        );
    }

    #[test]
    fn resolved_model_matching_the_configured_model_is_not_shown_twice() {
        assert_eq!(
            captured(|w| commit_message_generated(w, "OmniRoute", "gpt-5.4", Some("gpt-5.4"))),
            "Commit message generated by OmniRoute (gpt-5.4)\n"
        );
    }

    #[test]
    fn blank_line_writes_a_single_empty_line() {
        assert_eq!(captured(|w| blank_line(w)), "\n");
    }

    #[test]
    fn commit_lines_match_spec_wording() {
        assert_eq!(
            captured(|w| committing_using(w, "git commit -m ...")),
            "Committing using: git commit -m ...\n"
        );
        assert_eq!(
            captured(|w| committed_using(w, "git commit -m ...")),
            "Committed using: git commit -m ...\n"
        );
    }
}
